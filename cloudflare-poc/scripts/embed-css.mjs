import { readFileSync, writeFileSync } from "node:fs";
const font=(name)=>readFileSync(new URL("../src/fonts/"+name,import.meta.url)).toString("base64");
const css=readFileSync(".generated/ui.css","utf8")
 .replaceAll("__FONT_LATIN_EXT__","data:font/woff2;base64,"+font("geist-latin-ext.woff2"))
 .replaceAll("__FONT_LATIN__","data:font/woff2;base64,"+font("geist-latin.woff2"));
writeFileSync("src/generated-css.ts","// Generated by npm run ui:build; do not edit.\nexport default "+JSON.stringify(css)+";\n");
