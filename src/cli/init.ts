import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { parseArgs } from './parse-args.js';
import {
  INIT_FIELDS,
  INIT_MARKER_NAME,
  displayValue,
  type InitField,
} from './init-fields.js';
import { confirmYesNo, createPrompt, type Prompt } from './init-prompt.js';

interface InitMarker {
  initializedAt: string;
  envPath: string;
}

function parseEnvFile(content: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const eq = trimmed.indexOf('=');
    if (eq <= 0) {
      continue;
    }
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    result[key] = value;
  }
  return result;
}

function serializeEnv(values: Record<string, string>): string {
  const lines = [
    '# Generated by: npm run cli -- init',
    `# Updated: ${new Date().toISOString()}`,
    '',
    'NODE_ENV=production',
    `HOST=${values.HOST ?? '127.0.0.1'}`,
    `PORT=${values.PORT ?? '3210'}`,
    '',
    `EMBEDDED_PG=${values.EMBEDDED_PG ?? 'true'}`,
    `EMBEDDED_PG_DATA_DIR=${values.EMBEDDED_PG_DATA_DIR ?? '/var/lib/seqta-calendar/pg'}`,
    'EMBEDDED_PG_PORT=54329',
    'EMBEDDED_PG_USER=seqta',
    'EMBEDDED_PG_PASSWORD=seqta',
    'EMBEDDED_PG_DATABASE=seqta_calendar',
    '',
  ];

  if (values.EMBEDDED_PG === 'false' && values.DATABASE_URL) {
    lines.push(`DATABASE_URL=${values.DATABASE_URL}`, '');
  }

  lines.push(
    'DEFAULT_TIMEZONE=Australia/Sydney',
    `PUBLIC_BASE_URL=${values.PUBLIC_BASE_URL ?? ''}`,
    '',
    `TOKEN_PEPPER=${values.TOKEN_PEPPER ?? ''}`,
    `UID_SECRET=${values.UID_SECRET ?? ''}`,
    `SESSION_SECRET=${values.SESSION_SECRET ?? ''}`,
    '',
    `ALLOWED_ORIGINS=${values.ALLOWED_ORIGINS ?? ''}`,
    '',
    'MAX_BODY_BYTES=2097152',
    'MAX_LESSONS_PER_SYNC=2000',
    'MAX_SYNC_RANGE_DAYS=120',
    'CANCELLED_FEED_RETENTION_DAYS=14',
    '',
    `LOG_LEVEL=${values.LOG_LEVEL ?? 'info'}`,
    'TRUST_PROXY=true',
    'SESSION_TTL_HOURS=168',
    `COOKIE_SECURE=${values.COOKIE_SECURE ?? 'true'}`,
    `AUTH_DEV_LOGIN=${values.AUTH_DEV_LOGIN ?? 'false'}`,
    '',
    `OWNER_BOOTSTRAP_EMAIL=${values.OWNER_BOOTSTRAP_EMAIL ?? ''}`,
    `OWNER_BOOTSTRAP_PASSWORD=${values.OWNER_BOOTSTRAP_PASSWORD ?? ''}`,
    '',
  );

  return lines.join('\n');
}

function readMarker(markerPath: string): InitMarker | null {
  if (!existsSync(markerPath)) {
    return null;
  }
  try {
    return JSON.parse(readFileSync(markerPath, 'utf8')) as InitMarker;
  } catch {
    return { initializedAt: '(unknown)', envPath: markerPath };
  }
}

function loadCurrentValues(envPath: string): Record<string, string> {
  if (!existsSync(envPath)) {
    return {};
  }
  return parseEnvFile(readFileSync(envPath, 'utf8'));
}

async function askBool(prompt: Prompt, field: InitField, current: string): Promise<string> {
  const shown = current || field.defaultValue || 'false';
  const answer = await prompt.question(
    `${field.label}\n  当前: ${shown}\n  输入 true/false，留空保留: `,
  );
  if (!answer) {
    return current || field.defaultValue || 'false';
  }
  if (answer === 'true' || answer === '1' || answer === 'yes' || answer === 'y') {
    return 'true';
  }
  if (answer === 'false' || answer === '0' || answer === 'no' || answer === 'n') {
    return 'false';
  }
  console.log('无效布尔值，保留原值。');
  return current || field.defaultValue || 'false';
}

async function askField(
  prompt: Prompt,
  field: InitField,
  current: string,
  firstInit: boolean,
): Promise<string> {
  if (field.help) {
    console.log(`  说明: ${field.help}`);
  }

  if (field.kind === 'bool') {
    return askBool(prompt, field, current);
  }

  let effectiveCurrent = current;
  if (!effectiveCurrent && firstInit && field.autoGenerate) {
    effectiveCurrent = field.autoGenerate();
    console.log(`  将自动生成新密钥（首次初始化）`);
  }

  const shown = displayValue(field, effectiveCurrent || field.defaultValue || '');
  const hint = firstInit && field.requiredOnFirstInit && !effectiveCurrent && !field.autoGenerate
    ? '（必填）'
    : '留空保留';

  let answer: string;
  if (field.kind === 'password') {
    answer = await prompt.questionHidden(`${field.label}\n  当前: ${shown}\n  新值 ${hint}: `);
    if (answer) {
      const again = await prompt.questionHidden('  再输入一次确认: ');
      if (answer !== again) {
        console.log('两次输入不一致，保留原值。');
        return current || field.defaultValue || '';
      }
    }
  } else if (field.kind === 'secret') {
    answer = await prompt.question(
      `${field.label}\n  当前: ${shown}\n  新值 ${hint}（或输入 generate 重新生成）: `,
    );
    if (answer.toLowerCase() === 'generate' && field.autoGenerate) {
      answer = field.autoGenerate();
      console.log(`  已生成: ${displayValue(field, answer)}`);
    }
  } else {
    answer = await prompt.question(
      `${field.label}\n  当前: ${shown}\n  新值 ${hint}: `,
    );
  }

  if (!answer) {
    if (firstInit && !effectiveCurrent && field.defaultValue) {
      return field.defaultValue;
    }
    if (firstInit && !effectiveCurrent && field.autoGenerate) {
      return field.autoGenerate();
    }
    return effectiveCurrent || field.defaultValue || '';
  }
  return answer;
}

function printSummary(values: Record<string, string>): void {
  console.log('\n======== 即将保存的配置 ========');
  for (const field of INIT_FIELDS) {
    if (field.key === 'DATABASE_URL' && values.EMBEDDED_PG !== 'false') {
      continue;
    }
    if (field.key === 'EMBEDDED_PG_DATA_DIR' && values.EMBEDDED_PG === 'false') {
      continue;
    }
    console.log(`  ${field.key}=${displayValue(field, values[field.key] ?? '')}`);
  }
  console.log('================================\n');
}

function validateDraft(values: Record<string, string>, firstInit: boolean): string | null {
  if (!values.PUBLIC_BASE_URL) {
    return 'PUBLIC_BASE_URL 不能为空';
  }
  if (!values.TOKEN_PEPPER || !values.UID_SECRET || !values.SESSION_SECRET) {
    return 'TOKEN_PEPPER / UID_SECRET / SESSION_SECRET 不能为空';
  }
  if (values.TOKEN_PEPPER === values.UID_SECRET) {
    return 'TOKEN_PEPPER 与 UID_SECRET 必须不同';
  }
  if (values.EMBEDDED_PG === 'false' && !values.DATABASE_URL) {
    return 'EMBEDDED_PG=false 时必须提供 DATABASE_URL';
  }
  if (firstInit) {
    if (!values.OWNER_BOOTSTRAP_EMAIL?.includes('@')) {
      return '首次初始化需要有效的 OWNER_BOOTSTRAP_EMAIL';
    }
    if (!values.OWNER_BOOTSTRAP_PASSWORD || values.OWNER_BOOTSTRAP_PASSWORD.length < 8) {
      return '首次初始化需要至少 8 位的 OWNER_BOOTSTRAP_PASSWORD';
    }
  }
  return null;
}

export async function initCommand(args: string[]): Promise<void> {
  const options = parseArgs(args);
  const envPath = resolve(options.env || process.env.SEQTA_ENV_FILE || '.env');
  const markerPath = resolve(dirname(envPath), INIT_MARKER_NAME);
  const prompt = createPrompt();

  try {
    console.log('Seqta Link 交互式初始化');
    console.log(`环境文件: ${envPath}`);
    console.log(`标记文件: ${markerPath}\n`);

    const marker = readMarker(markerPath);
    const alreadyInitialized = Boolean(marker);
    let firstInit = !alreadyInitialized;

    if (alreadyInitialized) {
      console.log(`检测到已初始化（${marker!.initializedAt}）。`);
      const cont = await confirmYesNo(prompt, '是否继续重新配置？这不会自动覆盖，除非你最终确认保存');
      if (!cont) {
        console.log('已取消。');
        return;
      }
      firstInit = false;
    }

    const current = loadCurrentValues(envPath);
    const draft: Record<string, string> = { ...current };

    // Seed defaults for missing keys on first init
    if (firstInit) {
      for (const field of INIT_FIELDS) {
        if (!draft[field.key] && field.defaultValue) {
          draft[field.key] = field.defaultValue;
        }
      }
    }

    for (const field of INIT_FIELDS) {
      if (field.key === 'DATABASE_URL' && (draft.EMBEDDED_PG ?? 'true') !== 'false') {
        continue;
      }
      if (field.key === 'EMBEDDED_PG_DATA_DIR' && draft.EMBEDDED_PG === 'false') {
        continue;
      }

      console.log('');
      const before = draft[field.key] ?? '';
      const next = await askField(prompt, field, before, firstInit);

      if (next !== before && !firstInit) {
        console.log(
          `  将把 ${field.key} 从「${displayValue(field, before)}」改为「${displayValue(field, next)}」`,
        );
        const ok = await confirmYesNo(prompt, '确认更改这一项？');
        if (!ok) {
          console.log('  已跳过此项。');
          continue;
        }
      }
      draft[field.key] = next;
    }

    // Ensure secrets exist after loop
    for (const field of INIT_FIELDS) {
      if (field.autoGenerate && !draft[field.key]) {
        draft[field.key] = field.autoGenerate();
      }
    }

    const error = validateDraft(draft, firstInit || !marker);
    if (error) {
      console.error(`\n配置无效: ${error}`);
      process.exit(1);
    }

    printSummary(draft);
    const save = await confirmYesNo(prompt, '确认写入以上全部配置？');
    if (!save) {
      console.log('已取消，未写入任何文件。');
      return;
    }

    mkdirSync(dirname(envPath), { recursive: true });
    writeFileSync(envPath, serializeEnv(draft), { mode: 0o600 });
    const markerBody: InitMarker = {
      initializedAt: new Date().toISOString(),
      envPath,
    };
    writeFileSync(markerPath, `${JSON.stringify(markerBody, null, 2)}\n`, { mode: 0o600 });

    console.log(`\n已写入 ${envPath}`);
    console.log(`已更新标记 ${markerPath}`);
    console.log('\n下一步建议：');
    console.log('  1. npm run db:migrate');
    console.log('  2. npm run cli -- bootstrap-owner   # 若尚未创建 owner');
    console.log('  3. npm start / 启用 systemd 服务');
  } finally {
    prompt.close();
  }
}
